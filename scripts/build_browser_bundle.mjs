#!/usr/bin/env node

import { mkdirSync } from "node:fs";
import { resolve } from "node:path";
import { build } from "esbuild";

const outdir = resolve("dist");
mkdirSync(outdir, { recursive: true });

await build({
  entryPoints: [resolve("src/runtime.js")],
  outfile: resolve(outdir, "runtime.browser.js"),
  bundle: true,
  format: "esm",
  platform: "browser",
  target: "es2022",
  sourcemap: false,
  legalComments: "none",
  banner: {
    js: "// Rangefind browser runtime bundle. Generated by npm run build:browser."
  }
});

await build({
  // The regional and federated rfroutegraph-v1 query engines are
  // dependency-free browser-safe ESM; one bundle exposes both
  // openRouteGraphUrl() and openRouteCatalogUrl().
  entryPoints: [resolve("src/route.js")],
  outfile: resolve(outdir, "route.browser.js"),
  bundle: true,
  format: "esm",
  platform: "browser",
  target: "es2022",
  sourcemap: false,
  legalComments: "none",
  banner: {
    js: "// Rangefind route-graph query engine. Generated by npm run build:browser."
  }
});

await build({
  // The PulseMesh core — codecs, store, aggregation, validation, the
  // provider adapter — is dependency-free browser-safe ESM. libp2p is not
  // reachable from this entry point (it lives behind ./libp2p.js, which
  // index.js deliberately does not re-export), so this bundle stays small
  // and a page that only consumes live traffic pulls in no transport.
  entryPoints: [resolve("src/pulsemesh/index.js")],
  outfile: resolve(outdir, "pulsemesh.browser.js"),
  bundle: true,
  format: "esm",
  platform: "browser",
  target: "es2022",
  sourcemap: false,
  legalComments: "none",
  banner: {
    js: "// Rangefind PulseMesh core. Generated by npm run build:browser."
  }
});

await build({
  // The mobile contributor, for app hosts (the Android WebView engine,
  // React Native/Hermes). No transport: a phone consumes and contributes
  // through whatever network the host wires in, and needs none to run
  // the pipeline locally.
  entryPoints: [resolve("src/pulsemesh/mobile.js")],
  outfile: resolve(outdir, "pulsemesh.mobile.js"),
  bundle: true,
  format: "esm",
  platform: "browser",
  target: "es2022",
  sourcemap: false,
  legalComments: "none",
  banner: {
    js: "// Rangefind PulseMesh mobile contributor. Generated by npm run build:browser."
  }
});

await build({
  // The libp2p transport binding, for pages that join the real mesh. It
  // is an order of magnitude larger than the core, which is exactly why
  // it is a separate entry point loaded on demand rather than folded
  // into pulsemesh.browser.js.
  entryPoints: [resolve("src/pulsemesh/libp2p.js")],
  outfile: resolve(outdir, "pulsemesh-libp2p.browser.js"),
  bundle: true,
  format: "esm",
  platform: "browser",
  target: "es2022",
  sourcemap: false,
  legalComments: "none",
  banner: {
    js: "// Rangefind PulseMesh libp2p transport. Generated by npm run build:browser."
  }
});

await build({
  // The thread channel: WebCrypto only, so it needs no polyfill and no
  // transport either.
  entryPoints: [resolve("src/pulsemesh/threads.js")],
  outfile: resolve(outdir, "pulsemesh-threads.browser.js"),
  bundle: true,
  format: "esm",
  platform: "browser",
  target: "es2022",
  sourcemap: false,
  legalComments: "none",
  banner: {
    js: "// Rangefind PulseMesh threads. Generated by npm run build:browser."
  }
});

await build({
  // The QR encoder, for pages that have to put a capability on a screen a
  // camera can read — a dispatch ticket travels over no server, so the two
  // devices in the room are the channel. Pure computation, no dependency,
  // and small enough that a page loading it pays almost nothing.
  entryPoints: [resolve("src/qr.js")],
  outfile: resolve(outdir, "qr.browser.js"),
  bundle: true,
  format: "esm",
  platform: "browser",
  target: "es2022",
  sourcemap: false,
  legalComments: "none",
  banner: {
    js: "// Rangefind QR encoder. Generated by npm run build:browser."
  }
});

await build({
  // Bundle the complete browser-safe OSM surface, not only query.js. This
  // keeps the raw dist entry aligned with the `rangefind/osm` package export
  // (schema, documents, constraints, hours, route helpers, and adapters).
  entryPoints: [resolve("src/integrations/osm/index.js")],
  outfile: resolve(outdir, "osm.browser.js"),
  bundle: true,
  format: "esm",
  platform: "browser",
  target: "es2022",
  sourcemap: false,
  legalComments: "none",
  banner: {
    js: "// Rangefind OSM query integration. Generated by npm run build:browser."
  }
});
