#!/usr/bin/env node

// Bundles the <rangefind-search> custom element (and the runtime it imports)
// into a single self-contained ESM file, and copies the optional theme CSS
// alongside it. Zero runtime dependencies: everything is inlined here.

import { copyFileSync, mkdirSync } from "node:fs";
import { resolve } from "node:path";
import { build } from "esbuild";

const outdir = resolve("dist");
mkdirSync(outdir, { recursive: true });

await build({
  entryPoints: [resolve("src/rangefind_search_element.js")],
  outfile: resolve(outdir, "rangefind-search.js"),
  bundle: true,
  format: "esm",
  platform: "browser",
  target: "es2022",
  sourcemap: false,
  legalComments: "none",
  banner: {
    js: "// Rangefind <rangefind-search> web component. Generated by npm run build:element.\n"
      + "// Light DOM + headless: no styles injected. See dist/rangefind-search.css for the optional theme."
  }
});

// The theme is opt-in, so it ships as a plain stylesheet next to the bundle.
copyFileSync(resolve("src/rangefind-search.css"), resolve(outdir, "rangefind-search.css"));

// Stage the bundle + theme into the basic example's served root so the demo
// pages (component.html / component-tailwind.html) load them over a plain
// static server after `npm run serve:example`.
const demoDir = resolve("examples/basic/public");
try {
  mkdirSync(demoDir, { recursive: true });
  copyFileSync(resolve(outdir, "rangefind-search.js"), resolve(demoDir, "rangefind-search.js"));
  copyFileSync(resolve(outdir, "rangefind-search.css"), resolve(demoDir, "rangefind-search.css"));
} catch {
  // The example directory may not exist in a published package; ignore.
}

console.log("Built dist/rangefind-search.js and dist/rangefind-search.css");
