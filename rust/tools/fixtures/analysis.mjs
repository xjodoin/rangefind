function randomString() {
  const pools = [];
  const count = int(1, 3);
  for (let i = 0; i < count; i++) pools.push(pick(POOL_NAMES));
  const length = int(0, 48);
  let out = "";
  for (let i = 0; i < length; i++) {
    out += rand() < 0.18 ? " " : pick(POOLS[pick(pools)]);
  }
  return out;
}

