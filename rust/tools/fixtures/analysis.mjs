// mulberry32
function prng(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const rand = prng(0x5eed1234);
const pick = list => list[Math.floor(rand() * list.length)];
const int = (lo, hi) => lo + Math.floor(rand() * (hi - lo + 1));

// Lone surrogates (from UTF-16 slicing) become U+FFFD, matching Rust's lossy
// UTF-16 decode; JSON with lone surrogate escapes would not parse in serde.
function wellFormed(value) {
  if (typeof value === "string") return value.toWellFormed();
  if (Array.isArray(value)) return value.map(wellFormed);
  if (value && typeof value === "object") {
    const out = {};
    for (const [key, inner] of Object.entries(value)) out[key.toWellFormed()] = wellFormed(inner);
    return out;
  }
  return value;
}

function write(name, data) {
  const path = resolve(outDir, name);
  writeFileSync(path, JSON.stringify(wellFormed(data)));
  console.log(`wrote ${path}`);
}

