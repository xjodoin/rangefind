function bits(value) {
  // A NaN's sign and payload are unobservable in JS and differ by CPU (x86
  // produces 0xfff8..., arm64 0x7ff8...), so every NaN records as "nan".
  if (Number.isNaN(Number(value))) return "nan";
  const view = new DataView(new ArrayBuffer(8));
  view.setFloat64(0, Number(value));
  return view.getBigUint64(0).toString(16).padStart(16, "0");
}

// Rust strings cannot hold lone surrogates; the Rust readers decode them as
// U+FFFD (same UTF-16 length), so the expectation applies that mapping.
function wellFormed(value) {
  if (typeof value === "string") return value.toWellFormed();
  if (Array.isArray(value)) return value.map(wellFormed);
  if (value && typeof value === "object") {
    const out = {};
    for (const [key, item] of Object.entries(value)) out[wellFormed(key)] = wellFormed(item);
    return out;
  }
  return value;
}

function captureError(fn) {
  try {
    return { ok: fn() };
  } catch (error) {
    return { error: error.message };
  }
}

