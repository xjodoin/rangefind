function generatedAddress() {
  const number = pick(["", String(int(1, 99)), String(int(100, 9999)), `${int(1, 999)}${pick(["A", "B", "a", "c"])}`,
    `${int(1, 99)} ${pick(["A", "B", "c"])}`, `${int(100, 200)}-${int(201, 240)}`, `${int(1, 50)}-${int(1, 20)}`, "0", "007"]);
  const street = pick(STREET_NAMES);
  const type = pick(STREET_TYPES);
  const direction = pick(DIRECTIONS);
  const order = rand();
  let streetPart;
  if (order < 0.35) streetPart = `${type} ${street}`;
  else if (order < 0.85) streetPart = `${street} ${type}`;
  else streetPart = `${street}${type.toLowerCase().replace(/\.$/u, "")}`;
  const parts = [`${number} ${streetPart} ${direction}`.trim()];
  const unit = pick(UNITS);
  if (unit) {
    if (rand() < 0.5) parts[0] = `${parts[0]} ${unit}`;
    else parts.unshift(unit);
  }
  const locality = pick(LOCALITIES);
  if (locality) parts.push(locality);
  const region = pick(REGIONS);
  const postal = pick(POSTALS);
  const tail = `${region} ${postal}`.trim();
  if (tail) parts.push(tail);
  const sep = pick([", ", " ", ",", " , ", "  ", "\t", " - "]);
  let value = parts.join(sep);
  const mode = rand();
  if (mode < 0.12) value = value.toUpperCase();
  else if (mode < 0.24) value = value.toLowerCase();
  if (rand() < 0.1) value = `  ${value}  `;
  if (rand() < 0.05) value = value.replace(/ /gu, "\u00a0");
  return value;
}

