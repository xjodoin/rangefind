function cosCases() {
  const values = [0, -0, NaN, Infinity, -Infinity, Number.MIN_VALUE, -Number.MIN_VALUE, 1e-300, 2 ** -27, 2 ** -28,
    Math.PI / 4, Math.PI / 2, -Math.PI / 2, 3 * Math.PI / 4, Math.PI, 2 * Math.PI, 0.3, 0.78125, 0.7853981633974483,
    2 ** 19 * Math.PI / 2, 2 ** 20 * Math.PI / 2, 1e6, 1e10, 1e22, 1e100, 1e300, Number.MAX_VALUE, -Number.MAX_VALUE,
    2 ** 1023, 6381956970095103 * 2 ** 797, 5.319372648326541e+255, 1.2e9, -3.7e15];
  for (let n = 1; n <= 40; n++) values.push(n * Math.PI / 2, -n * Math.PI / 2, n * Math.PI / 2 + 1e-12);
  for (let index = 0; index < 4000; index++) values.push((rand() * 2 - 1) * pick([1, 4, 40, 400, 1e4, 1e6, 1e9]));
  for (let index = 0; index < 4000; index++) values.push((rand() < 0.5 ? -1 : 1) * rand() * 2 ** int(-60, 1023));
  // Geometry-shaped arguments: (lat + lat) * PI / 360 over the decodable range.
  for (let index = 0; index < 4000; index++) values.push((rand() * 4400 - 2200) * Math.PI / 360);
  return values.map(value => [bits(value), bits(Math.cos(value))]);
}

