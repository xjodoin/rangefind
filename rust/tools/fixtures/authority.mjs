function byteCompare(left, right) {
  return Buffer.compare(Buffer.from(left, "utf8"), Buffer.from(right, "utf8"));
}

function generateAbbreviations() {
  const lines = [];
  lines.push("//! Generated by `node rust/tools/fixtures/authority.mjs` from");
  lines.push("//! `src/address_abbreviations.js` — do not edit. Keys are sorted by byte");
  lines.push("//! order for binary search; `CONCATENATED_SUFFIX_READINGS` keeps the JS");
  lines.push("//! `Map` iteration order.");
  lines.push("");
  lines.push("/// `ADDRESS_TOKEN_READINGS`: token -> alternative readings (token lists).");
  lines.push("pub static ADDRESS_TOKEN_READINGS: &[(&str, &[&[&str]])] = &[");
  const readings = [...abbreviations.ADDRESS_TOKEN_READINGS.entries()].sort((a, b) => byteCompare(a[0], b[0]));
  for (const [key, list] of readings) {
    const items = list.map(reading => `&[${reading.map(rustString).join(", ")}]`).join(", ");
    lines.push(`    (${rustString(key)}, &[${items}]),`);
  }
  lines.push("];");
  lines.push("");
  const set = (name, doc, values) => {
    lines.push(`/// \`${doc}\` (sorted by byte order).`);
    lines.push(`pub static ${name}: &[&str] = &[`);
    const sorted = [...values].sort(byteCompare);
    for (let index = 0; index < sorted.length; index += 8) {
      lines.push(`    ${sorted.slice(index, index + 8).map(rustString).join(", ")},`);
    }
    lines.push("];");
    lines.push("");
  };
  set("CONCATENATED_STREET_SUFFIXES", "CONCATENATED_STREET_SUFFIXES", abbreviations.CONCATENATED_STREET_SUFFIXES);
  lines.push("/// `CONCATENATED_SUFFIX_READINGS` in JS `Map` order: abbreviation -> expansions.");
  lines.push("pub static CONCATENATED_SUFFIX_READINGS: &[(&str, &[&str])] = &[");
  for (const [abbrev, expansions] of abbreviations.CONCATENATED_SUFFIX_READINGS) {
    lines.push(`    (${rustString(abbrev)}, &[${expansions.map(rustString).join(", ")}]),`);
  }
  lines.push("];");
  lines.push("");
  set("STREET_TYPE_TOKENS", "STREET_TYPE_TOKENS", abbreviations.STREET_TYPE_TOKENS);
  const text = `${lines.join("\n").trimEnd()}\n`;
  const target = resolve(repo, "rust/rangefind/src/authority/abbreviations.rs");
  let previous = "";
  try {
    previous = readFileSync(target, "utf8");
  } catch {
    // first generation
  }
  if (previous !== text) {
    writeFileSync(target, text);
    console.log(`regenerated ${target}`);
  }
  write("tables.json", {
    readings: [...abbreviations.ADDRESS_TOKEN_READINGS.entries()],
    concatenatedStreetSuffixes: [...abbreviations.CONCATENATED_STREET_SUFFIXES],
    concatenatedSuffixReadings: [...abbreviations.CONCATENATED_SUFFIX_READINGS.entries()],
    streetTypeTokens: [...abbreviations.STREET_TYPE_TOKENS],
    tokenAliases: [...address.TOKEN_ALIASES.entries()]
  });
}

