const DISPLAYS = ["Paris", "paris", "Paris, France", "Parïs", "Pâris", "PARIS!", "Montréal", "Montreal", "東京",
  "東京 Tokyo", "😀 Smile", "Smile", "a", "", "Ab", "AB", "ab", "Rue de l'Église", "Saint-Laurent", "Saint Laurent"];
const NORMALIZED = ["paris", "paris france", "montreal", "東京", "東京 tokyo", "smile", "a", "", "ab", "rue de l eglise",
  "saint laurent", "laurent", "france", "tokyo"];

function rankCases() {
  const ranks = [];
  for (let index = 0; index < 600; index++) {
    const weight = pick([0, 1, 2, 7, 1000, 2 ** 31, 2 ** 32 - 1, 2 ** 32, 2 ** 33, 2 ** 52, 2 ** 53, -5, 2.9, NaN, Infinity, -Infinity, "12", "x", null]);
    const full = pick([true, false, undefined, null]);
    const display = pick(DISPLAYS);
    const normalized = pick(NORMALIZED);
    const item = { weight, display, normalized, ...(full !== undefined ? { full } : {}) };
    const weighted = rand() < 0.5;
    ranks.push({
      weight: typeof weight === "number" ? bits(weight) : weight,
      weightKind: typeof weight,
      full: full === undefined ? "undefined" : full,
      display,
      normalized,
      weighted,
      rank: bits(lexicon.autocompleteRank(item, weighted))
    });
  }
  const items = [];
  for (let index = 0; index < 160; index++) {
    const item = {
      display: pick(DISPLAYS),
      normalized: pick(NORMALIZED),
      weight: pick([0, 1, 2, 3, 5, 5, 9, NaN]),
      ...(rand() < 0.7 ? { rank: pick([0, 1, 2, 3, 4, 2 ** 32, 2 ** 32 + 1, NaN]) } : {})
    };
    items.push(item);
  }
  const encode = item => ({
    display: item.display,
    normalized: item.normalized,
    weight: bits(item.weight),
    rank: item.rank === undefined ? null : bits(item.rank)
  });
  const pairs = [];
  for (let index = 0; index < 1500; index++) {
    const left = pick(items);
    const right = pick(items);
    pairs.push({ left: items.indexOf(left), right: items.indexOf(right), sign: Math.sign(lexicon.compareAutocomplete({ ...left }, { ...right })) || 0 });
  }
  const sorts = [];
  for (let index = 0; index < 40; index++) {
    const list = Array.from({ length: int(0, 30) }, () => int(0, items.length - 1));
    // NaN ranks make the comparator inconsistent; keep sorted lists to
    // NaN-free items so the result does not depend on the sort algorithm.
    const clean = list.filter(position => !Number.isNaN(items[position].rank ?? items[position].weight));
    const sorted = clean.map(position => ({ ...items[position], position })).sort(lexicon.compareAutocomplete);
    sorts.push({ input: clean, output: sorted.map(item => item.position) });
  }
  return { ranks, items: items.map(encode), pairs, sorts };
}

