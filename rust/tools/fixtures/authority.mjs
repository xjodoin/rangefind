function lexiconRootCases() {
  const cases = [];
  for (let index = 0; index < 80; index++) {
    const shards = [];
    const names = new Set();
    const count = int(0, 25);
    for (let item = 0; item < count; item++) {
      const shard = `s|${pick(KEY_WORDS)}${pick(["", "a", "b", "😀", "é"])}`;
      if (names.has(shard)) continue;
      names.add(shard);
      shards.push({ shard, maxRank: int(0, rand() < 0.2 ? 2 ** 40 : 1000), count: int(0, 5000) });
    }
    const hot = new Map();
    const hotCount = int(0, 8);
    for (let item = 0; item < hotCount; item++) {
      hot.set(pick(["a", "b", "ab", "abc", "é", "東", "😀", "z", "mo"]), {
        file: `authority/hot/${int(0, 1e6).toString(16)}.bin.gz`, bytes: int(0, 100000), count: int(0, 64)
      });
    }
    const buffer = lexicon.encodeAuthorityLexiconRoot({ shards, hot, weighted: rand() < 0.5 });
    const parsed = lexicon.parseAuthorityLexiconRoot(buffer);
    cases.push({ bytes: b64(buffer), result: wellFormed({ ...parsed, hot: [...parsed.hot.entries()] }) });
  }
  const edges = [
    Buffer.from([0x52, 0x46, 0x4c]), Buffer.from([...binary.AUTHORITY_LEXICON_MAGIC, 2, 0, 0, 0]),
    Buffer.from([...binary.AUTHORITY_LEXICON_MAGIC, 1, 0, 0, 0, 9]), Buffer.from([...binary.AUTHORITY_LEXICON_MAGIC, 1, 1, 1, 0]),
    Buffer.from([...binary.AUTHORITY_LEXICON_MAGIC, 1, 3, 0, 0]),
    // Duplicate hot prefix: the later value replaces the earlier in place.
    (() => {
      const out = [...binary.AUTHORITY_LEXICON_MAGIC];
      binary.pushVarint(out, 1); binary.pushVarint(out, 0); binary.pushVarint(out, 0); binary.pushVarint(out, 3);
      for (const [prefix, file] of [["a", "one"], ["b", "two"], ["a", "three"]]) {
        pushUtf8(out, prefix); pushUtf8(out, file); binary.pushVarint(out, 5); binary.pushVarint(out, 6);
      }
      return Buffer.from(out);
    })()
  ];
  for (const buffer of edges) {
    const result = captureError(() => {
      const parsed = lexicon.parseAuthorityLexiconRoot(buffer);
      return { ...parsed, hot: [...parsed.hot.entries()] };
    });
    cases.push({ bytes: b64(buffer), ...(result.error ? { error: result.error } : { result: result.ok }) });
  }
  return cases;
}

