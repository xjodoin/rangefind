function hotListLegacy(version, entries) {
  const out = [...binary.AUTHORITY_HOT_MAGIC];
  binary.pushVarint(out, version);
  binary.pushVarint(out, entries.length);
  for (const entry of entries) {
    pushUtf8(out, entry.normalized);
    pushUtf8(out, entry.display);
    binary.pushVarint(out, entry.weight);
    binary.pushVarint(out, entry.count);
    if (version === 2) binary.pushVarint(out, entry.doc == null ? 0 : entry.doc + 1);
  }
  return Buffer.from(out);
}

