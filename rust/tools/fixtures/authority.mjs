function ranges(predicate) {
  const out = [];
  let start = -1;
  for (let cp = 0; cp <= 0x110000; cp++) {
    const inside = cp < 0x110000 && !(cp >= 0xd800 && cp <= 0xdfff) && predicate(cp);
    if (inside && start < 0) start = cp;
    if (!inside && start >= 0) {
      out.push([start, cp - 1]);
      start = -1;
    }
  }
  return out;
}

function unicodeFixture() {
  const letterNumber = /^[\p{L}\p{N}]$/u;
  const space = /^\s$/u;
  const wordIu = /^\w$/iu;
  const word = /^\w$/u;
  const fsa = /^[abceghj-nprstvxy]$/iu;
  const ldu = /^[abceghj-nprstvwxyz]$/iu;
  const digit = /^\d$/iu;
  const unassigned = /^\p{Cn}$/u;
  const charOf = cp => String.fromCodePoint(cp);
  const mapped = transform => {
    const out = [];
    for (let cp = 0; cp < 0x110000; cp++) {
      if (cp >= 0xd800 && cp <= 0xdfff) continue;
      const ch = charOf(cp);
      const value = transform(ch);
      if (value !== ch) out.push([cp, value]);
    }
    return out;
  };
  return {
    unicode: process.versions.unicode,
    letterNumber: ranges(cp => letterNumber.test(charOf(cp))),
    space: ranges(cp => space.test(charOf(cp))),
    trimmed: ranges(cp => charOf(cp).trim() === ""),
    wordIu: ranges(cp => wordIu.test(charOf(cp))),
    word: ranges(cp => word.test(charOf(cp))),
    fsa: ranges(cp => fsa.test(charOf(cp))),
    ldu: ranges(cp => ldu.test(charOf(cp))),
    digit: ranges(cp => digit.test(charOf(cp))),
    unassigned: ranges(cp => unassigned.test(charOf(cp))),
    nfkcLower: mapped(ch => ch.normalize("NFKC").toLowerCase()),
    fold: mapped(ch => foldMulti(ch))
  };
}

